const LanguageContext = createContext(null);
const supportedLanguages = ["en", "fil", "ceb"];

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const saved = localStorage.getItem("resq_language");
    return supportedLanguages.includes(saved) ? saved : "en";
  });

  const setLanguage = useCallback((value) => {
    const next = supportedLanguages.includes(value) ? value : "en";
    localStorage.setItem("resq_language", next);
    document.documentElement.lang = next;
    setLanguageState(next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback((text) => translations[language]?.[text] || text, [language]);
  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used within LanguageProvider.");
  return context;
}
